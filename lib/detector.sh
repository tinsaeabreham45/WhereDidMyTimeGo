# shellcheck shell=bash
#
# KWin detector for WhereDidMyTimeGo.
#
# KWin 6 does not expose the focused window through a plain D-Bus property.
# Instead we load a tiny KWin script. The script sends an event through
# callDBus whenever the active window changes. A busctl monitor in the tracker
# observes those messages and hands them to the Bash daemon as JSON lines.
#
# The script sends application identifiers only. It never sends window titles,
# window contents, or keystrokes.

write_kwin_script() {
    local path=${1:?script path required}
    local token=${2:?run token required}
    local tmp="${path}.tmp.$$"

    cat >"$tmp" <<'JS'
/*
 * WhereDidMyTimeGo KWin helper.
 *
 * This file is generated by lib/detector.sh and loaded through
 * org.kde.KWin /Scripting. It sends a small JSON payload for the active
 * window. It intentionally does not read window titles or contents.
 */
var WDMTG_SERVICE = "org.wheredidmytimego.Tracker";
var WDMTG_OBJECT = "/org/wheredidmytimego/Tracker";
var WDMTG_IFACE = "org.wheredidmytimego.Tracker";
var WDMTG_TOKEN = "__WDMTG_TOKEN__";

function wdmtgString(value) {
    return (value === undefined || value === null) ? "" : String(value);
}

function wdmtgSend(eventName, window) {
    var payload = {
        token: WDMTG_TOKEN,
        event: eventName,
        app_class: window ? wdmtgString(window.resourceClass) : "",
        app_name: window ? wdmtgString(window.resourceName) : "",
        desktop_file: window ? wdmtgString(window.desktopFileName) : "",
        pid: window ? (Number(window.pid) || 0) : 0
    };
    callDBus(WDMTG_SERVICE, WDMTG_OBJECT, WDMTG_IFACE, "Event",
             JSON.stringify(payload));
}

function wdmtgActive(window) {
    if (window) {
        wdmtgSend("active", window);
    } else {
        wdmtgSend("none", null);
    }
}

workspace.windowActivated.connect(wdmtgActive);
wdmtgActive(workspace.activeWindow);
JS

    # The token is generated from digits and a hyphen, so it is safe in sed.
    sed -i "s/__WDMTG_TOKEN__/${token}/g" "$tmp" || return 1
    chmod 600 -- "$tmp" || return 1
    mv -f -- "$tmp" "$path" || return 1
    return 0
}

# Remove the plugin without requiring WDMTG_SCRIPT_LOADED to be set. After a
# crashed run KWin can still know about the old plugin even if isScriptLoaded
# reports false, and loading the same name too soon then returns -1.
detector_unload_quiet() {
    qdbus6 org.kde.KWin /Scripting \
        org.kde.kwin.Scripting.unloadScript "$WDMTG_KWIN_PLUGIN" \
        >/dev/null 2>&1 || true
    WDMTG_SCRIPT_LOADED=0
    WDMTG_SCRIPT_ID=""
}

# Load (or reload) the KWin helper. Sets WDMTG_SCRIPT_ID and
# WDMTG_SCRIPT_LOADED. Returns non-zero with a diagnostic on failure.
detector_load() {
    local path=$WDMTG_SCRIPT_FILE
    local token=$WDMTG_RUN_ID
    local out attempt

    # Clear any stale helper from a crashed run before writing the new one.
    detector_unload_quiet
    rm -f -- "$path"

    write_kwin_script "$path" "$token" || {
        printf 'could not write KWin helper: %s\n' "$path" >&2
        return 1
    }

    for attempt in 1 2; do
        if out=$(qdbus6 org.kde.KWin /Scripting \
            org.kde.kwin.Scripting.loadScript "$path" "$WDMTG_KWIN_PLUGIN" 2>&1) &&
            [[ $out =~ ^[0-9]+$ ]] && ((out >= 0)); then
            break
        fi

        printf 'KWin loadScript attempt %s failed: %s\n' "$attempt" "$out" >&2
        detector_unload_quiet
        if ((attempt == 1)); then
            sleep 0.3
        else
            detector_stop || true
            return 1
        fi
    done

    WDMTG_SCRIPT_LOADED=1
    WDMTG_SCRIPT_ID=$out

    if ! out=$(qdbus6 org.kde.KWin "/Scripting/Script${WDMTG_SCRIPT_ID}" \
        org.kde.kwin.Script.run 2>&1); then
        printf 'KWin Script.run failed: %s\n' "$out" >&2
        detector_stop || true
        return 1
    fi

    return 0
}

detector_reload() {
    detector_stop || true
    detector_load
}

detector_stop() {
    local out

    if [[ ${WDMTG_SCRIPT_LOADED:-0} == 1 ]]; then
        if ! out=$(qdbus6 org.kde.KWin /Scripting \
            org.kde.kwin.Scripting.unloadScript "$WDMTG_KWIN_PLUGIN" 2>&1); then
            printf 'KWin unloadScript failed: %s\n' "$out" >&2
        elif [[ $out != "true" ]]; then
            printf 'KWin unloadScript returned: %s\n' "$out" >&2
        fi
        WDMTG_SCRIPT_LOADED=0
    fi

    rm -f -- "$WDMTG_SCRIPT_FILE"
    return 0
}

# Parse one busctl monitor JSON line. Prints five tab-separated fields:
# event, app_class, app_name, desktop_file, pid.
# KWin events are "active"/"none"; screen-lock changes are "lock"/"unlock".
# Returns 1 for malformed lines or events belonging to another tracker run.
parse_monitor_line() {
    local raw=${1-}
    local token=${2-}
    local output

    [[ -n $raw && -n $token ]] || return 1

    output=$(printf '%s\n' "$raw" | jq -r --arg token "$token" --arg iface "$WDMTG_INTERFACE" '
        if .member == "Event" and .interface == $iface then
            .payload.data[0]
            | fromjson
            | select(.token == $token)
            | [
                .event,
                .app_class,
                .app_name,
                .desktop_file,
                (.pid | tostring)
              ]
            | @tsv
        elif .member == "ActiveChanged" and
             .interface == "org.freedesktop.ScreenSaver" then
            [
                (if .payload.data[0] then "lock" else "unlock" end),
                "",
                "",
                "",
                "0"
            ]
            | @tsv
        else
            empty
        end
    ' 2>&1) || return 1

    [[ -n $output ]] || return 1
    printf '%s\n' "$output"
}
